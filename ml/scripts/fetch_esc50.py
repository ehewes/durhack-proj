"""Download a small, licence-tracked set of night background sounds from ESC-50.

Saves 16 kHz mono 16-bit WAV clips under ml/audio/online/background/<category>/ and rewrites
the ESC-50 part of ml/audio/SOURCES.md. Re-running is safe: existing files are skipped.

    uv run ml/scripts/fetch_esc50.py [--per-class 6]
"""
import argparse, csv, io, sys, urllib.request, wave
from concurrent.futures import ThreadPoolExecutor
from math import gcd
from pathlib import Path

import numpy as np
from scipy.signal import resample_poly

BASE = "https://raw.githubusercontent.com/karolpiczak/ESC-50/master"
ROOT = Path(__file__).resolve().parents[1] / "audio"
OUT = ROOT / "online" / "background"
RATE = 16000
UA = {"User-Agent": "kip-hackathon-dataset-script/0.1"}

# ESC-50 category -> our background category
CATEGORIES = {
    "engine": "traffic", "car_horn": "traffic", "siren": "siren",
    "chainsaw": "construction", "hand_saw": "construction",
    "airplane": "aircraft", "helicopter": "aircraft", "train": "rail",
    "snoring": "snoring", "breathing": "breathing",
    "rain": "weather", "wind": "weather",
    "clock_tick": "room", "door_wood_creaks": "room", "footsteps": "footsteps",
}


def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
        return r.read()


def to_16k_mono(data):
    with wave.open(io.BytesIO(data)) as w:
        ch, width, rate = w.getnchannels(), w.getsampwidth(), w.getframerate()
        frames = w.readframes(w.getnframes())
    if width != 2:
        raise ValueError("expected 16-bit PCM")
    x = np.frombuffer(frames, dtype="<i2").astype(np.float32).reshape(-1, ch).mean(axis=1)
    g = gcd(RATE, rate)
    y = resample_poly(x, RATE // g, rate // g)
    return np.clip(np.round(y), -32768, 32767).astype("<i2").tobytes()


def write_wav(path, pcm):
    path.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(RATE); w.writeframes(pcm)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--per-class", type=int, default=6)
    args = ap.parse_args()

    rows = list(csv.DictReader(io.StringIO(get(BASE + "/meta/esc50.csv").decode())))
    picks = []
    for esc_cat, ours in CATEGORIES.items():
        clips = sorted((r for r in rows if r["category"] == esc_cat), key=lambda r: (int(r["fold"]), r["filename"]))
        by_fold = {}
        for r in clips:
            by_fold.setdefault(r["fold"], []).append(r)
        chosen, i = [], 0  # round-robin across folds for variety
        while len(chosen) < args.per_class and any(by_fold.values()):
            fold = sorted(by_fold)[i % len(by_fold)]
            if by_fold[fold]:
                chosen.append(by_fold[fold].pop(0))
            i += 1
        picks += [(r, ours) for r in chosen]

    def fetch(item):
        r, ours = item
        dest = OUT / ours / f"esc50_{r['category']}_{r['filename']}"
        if not dest.exists():
            write_wav(dest, to_16k_mono(get(f"{BASE}/audio/{r['filename']}")))
        return r, ours, dest

    with ThreadPoolExecutor(8) as pool:
        done = list(pool.map(fetch, picks))

    lines = ["## ESC-50 (background sounds)", "",
             "Source: K. J. Piczak, *ESC: Dataset for Environmental Sound Classification*, ACM Multimedia 2015, "
             "<https://github.com/karolpiczak/ESC-50>. Licence: **CC BY-NC 3.0** (non-commercial use, attribution). "
             "Clips come from Freesound field recordings; resampled to 16 kHz mono here.", "",
             "| File | ESC-50 category | Our category | Freesound source |", "|---|---|---|---|"]
    for r, ours, dest in sorted(done, key=lambda t: str(t[2])):
        lines.append(f"| `{dest.relative_to(ROOT)}` | {r['category']} | {ours} | <https://freesound.org/s/{r['src_file']}/> |")
    write_section("ESC-50", "\n".join(lines))
    print(f"{len(done)} clips in {OUT.relative_to(ROOT.parent.parent)}")


def write_section(name, text):
    """Replace one generated section of SOURCES.md, keeping the others."""
    path = ROOT / "SOURCES.md"
    head = "# Audio sources and licences\n\nGenerated by the scripts in `ml/scripts/`. Do not edit by hand.\n"
    sections = {}
    if path.exists():
        for block in path.read_text().split("<!-- section:")[1:]:
            key, _, body = block.partition(" -->\n")
            sections[key] = body.split("<!-- end -->")[0].strip()
    sections[name] = text
    out = head + "".join(f"\n<!-- section:{k} -->\n{v}\n<!-- end -->\n" for k, v in sorted(sections.items()))
    path.write_text(out)


if __name__ == "__main__":
    sys.exit(main())
