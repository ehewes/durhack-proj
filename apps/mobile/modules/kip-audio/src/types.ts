// The frozen JS surface of kip-audio (docs/ARCHITECTURE.md, "Contracts"). Changing it needs a platform issue.

/** Spike clips are 16 kHz mono 16-bit PCM WAV, so the server needs no audio decoder. */
export const CLIP_FORMAT = {
  sampleRateHz: 16_000,
  channels: 1,
  bitDepth: 16,
  container: "wav",
} as const;

/** Seconds of audio kept around each spike (docs/DOMAIN.md, "Bedroom noise"). */
export const CLIP_SECONDS = 10;

export type StartOptions = {
  /** Spike = level this many dB above the night's rolling median. Comes from `packages/shared`. */
  spikeThresholdDb: number;
};

/** One metering sample, once a second. The phone mic is uncalibrated, so the level is relative dB only. */
export type AudioSample = {
  /** Unix epoch milliseconds. */
  t: number;
  /** Level in dB relative to the night's own baseline. Not calibrated SPL. */
  relativeDb: number;
  /** True when the value was generated by the web stub, never measured. */
  simulated: boolean;
};

type SpikeBase = {
  /** Unix epoch milliseconds of the peak. */
  t: number;
  /** Peak level in relative dB. */
  peakDb: number;
  simulated: boolean;
};

/**
 * Either a clip was kept (`clipUri` points at a 16 kHz mono 16-bit WAV in app storage) or the
 * on-device speech check dropped it (`speechDropped`, no audio exists). Never both.
 */
export type SpikeEvent =
  | (SpikeBase & { clipUri: string; speechDropped?: false })
  | (SpikeBase & { speechDropped: true; clipUri?: undefined });

export type Unsubscribe = () => void;

/** What each platform implementation (`KipAudioModule.ts` native, `.web.ts` stub) provides. */
export type KipAudioNative = {
  start(options: StartOptions): Promise<void>;
  stop(): Promise<void>;
  isRecording(): boolean;
  deleteClip(uri: string): Promise<void>;
  addListener(event: "onSample", cb: (s: AudioSample) => void): { remove(): void };
  addListener(event: "onSpike", cb: (s: SpikeEvent) => void): { remove(): void };
};
